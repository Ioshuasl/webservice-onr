function cardTitle(ep, planeSeq) {
  const n = planeSeq ?? ep.seq;
  return `[AUTSEETJGO-${n}] (see tjgo) ${ep.operacao} - ${ep.dominio}`;
}

function planeKey(ep) {
  return `AUTSEETJGO-${ep.seq}`;
}

function specFilename(ep) {
  const slug = ep.upstream
    .replace(/^\//, '')
    .replace(/\{[^}]+\}/g, 'id')
    .replace(/\//g, '-');
  return `endpoints/${ep.method.toLowerCase()}-${slug}.md`;
}

function workflowFilename(ep) {
  const words = ep.operacao.replace(/([A-Z])/g, ' $1').trim();
  return `${words} SEE TJGO.workflow.ts`;
}

function webhookPath(ep) {
  return ep.webhook.replace(/^(GET|POST|PUT|DELETE|PATCH) /, '').replace(/^\//, '');
}

function bySeq(seq) {
  return ENDPOINTS.find((e) => e.seq === seq);
}

